// Token Radar, model radar-2: one snapshot of the protocol universe in, one ranked board out.
//
// The board ranks every protocol the radar may rank: the snapshot's whole watchlist (the floor,
// never a ceiling) plus every other pre-token protocol that is not a wrapped, staked or bridged
// product of a token that already trades. A protocol is pre-token when its record carries no token
// (no market cap, no CoinGecko id, no symbol). Live-token protocols are kept apart and shown with
// the market's own values, never mixed into the ranking -- and they are also the model's evidence.
//
// Implied value follows only from the snapshot's own figures, through category comparables:
//
//   peer multiple  = median(market cap / TVL) over the live-token protocols in the same category
//                    (at least 2 peers; otherwise the global median over all live-token
//                    protocols), clamped to [0.05, 1.00]
//   base           = tvl_usd x peer multiple
//   growth         = clamp(change_7d, -60, 120) per cent
//   growthMult     = 1 + (growth / 100) x GROWTH_WEIGHT
//   maturity       = 0.6 + min(age_days, 1095) / 1095 x 0.4   (age_days unknown: 365)
//   breadth        = 1 + 0.03 x min(chains - 1, 5)           (more chains, more surface)
//   implied        = max(1, round(base x growthMult x maturity x breadth))
//
// The peer multiple is the point: a lending protocol is priced like lending protocols that
// already trade, a DEX like DEXes, not like everything at one flat rate. No protocol name is
// ever special-cased: the same function scores every row, and every row carries the peers
// behind its multiple so a reader can check the arithmetic.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

