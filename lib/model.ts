/** Why the snapshot is not one this model can score. */
export class SnapshotError extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'SnapshotError';
  }
}

const DAY_MS = 86_400_000;

/** A finite number, else `fallback`. */
function finite(value: unknown, fallback: number): number {
  return typeof value === 'number' && Number.isFinite(value) ? value : fallback;
}

/** A whole day count from `from` to `to`, clamped at zero; null when either date is absent or bad. */
export function ageDays(asOf: string, listedAt: string | null): number | null {
  if (listedAt === null) return null;
  const a = Date.parse(`${asOf}T00:00:00Z`);
  const b = Date.parse(`${listedAt}T00:00:00Z`);
  if (!Number.isFinite(a) || !Number.isFinite(b)) return null;
  return Math.max(0, Math.floor((a - b) / DAY_MS));
}

/** The median of a sorted-ascending list, or null when it is empty. */
function median(sorted: number[]): number | null {
  if (sorted.length === 0) return null;
  const mid = Math.floor(sorted.length / 2);
  return sorted.length % 2 === 1 ? sorted[mid]! : (sorted[mid - 1]! + sorted[mid]!) / 2;
}

/** The median of a list, unsorted in, or null when empty. */
function medianOf(values: number[]): number | null {
  return median([...values].sort((a, b) => a - b));
}

/** DefiLlama's version-marker rule: a name ending in a release is a pool of another protocol. */
const VERSIONED = /\s(V\d+(\.\d+)?|v\d+(\.\d+)?|\d+\.\d+)$/;

/** Categories that are a wrapped, staked or bridged product of a token that already trades. */
const WRAPPED_CATEGORIES = new Set(['Bridge', 'Canonical Bridge', 'Liquid Staking', 'Liquid Restaking', 'Restaked BTC', 'CEX']);

/** Exchange names: a protocol beginning with one is the exchange's own product, not a launch. */
const EXCHANGE_NAMES = ['Binance', 'Coinbase', 'Bybit', 'Kraken', 'Bitget', 'OKX', 'Bitfinex', 'Gemini'];

/** A whole word wrapped, staked or staking anywhere in the name. */
const WRAPPED_WORD = /\b(wrapped|staked|staking)\b/i;

/** Whether a protocol records no token at all. */
export function isPreToken(p: SnapshotProtocol): boolean {
  return p.mcap_usd === null && p.gecko_id === null && p.symbol === null;
}

/**
 * Whether a protocol is one the board may rank: pre-token, and not a wrapped, staked or bridged
 * product of a protocol whose token already trades (the house watchlist rule, applied to the
 * whole universe so the early radar finds launches, not wrappers).
 */
export function isRankable(p: SnapshotProtocol): boolean {
  if (!isPreToken(p)) return false;
  if (p.category !== null && WRAPPED_CATEGORIES.has(p.category)) return false;
  if (VERSIONED.test(p.name)) return false;
  if (WRAPPED_WORD.test(p.name)) return false;
  if (EXCHANGE_NAMES.some((e) => p.name === e || p.name.startsWith(`${e} `))) return false;
  return true;
}

/** The snapshot's protocol by slug. */
function bySlug(protocols: SnapshotProtocol[]): Map<string, SnapshotProtocol> {
  return new Map(protocols.map((p) => [p.slug, p]));
}

/** The comparables table: one median market-cap/TVL multiple per category, from live tokens. */
export function buildComparables(snapshot: Snapshot, model: ModelConstants = MODEL): Record<string, CategoryComparable> {
  const live = snapshot.protocols.filter((p) => !isPreToken(p) && p.tvl_usd > 0 && (p.mcap_usd ?? 0) > 0);
  const global = medianOf(live.map((p) => p.mcap_usd! / p.tvl_usd)) ?? model.multiple_floor;
  const byCategory = new Map<string, SnapshotProtocol[]>();
  for (const p of live) {
    const key = p.category ?? 'Other';
    const list = byCategory.get(key) ?? [];
    list.push(p);
    byCategory.set(key, list);
  }
  const out: Record<string, CategoryComparable> = {};
  for (const [category, peers] of byCategory) {
    const ratios = peers.map((p) => p.mcap_usd! / p.tvl_usd);
    const med = medianOf(ratios);
    const useGlobal = peers.length < model.min_peers || med === null;
    const multiple = Math.min(model.multiple_cap, Math.max(model.multiple_floor, useGlobal ? global : med!));
    out[category] = {
      multiple: Math.round(multiple * 1e4) / 1e4,
      peers: peers.length,
      examples: [...peers]
        .sort((a, b) => (b.mcap_usd ?? 0) - (a.mcap_usd ?? 0))
        .slice(0, 3)
        .map((p) => p.name),
    };
  }
  // The fallback category itself, for protocols whose category has no live peers at all.
  out['Other'] = out['Other'] ?? {
    multiple: Math.round(Math.min(model.multiple_cap, Math.max(model.multiple_floor, global)) * 1e4) / 1e4,
    peers: 0,
    examples: [],
  };
  return out;
}

/** The global peer multiple: the median market-cap/TVL over every live-token protocol. */
export function globalPeerMultiple(snapshot: Snapshot, model: ModelConstants = MODEL): number {
  const live = snapshot.protocols.filter((p) => !isPreToken(p) && p.tvl_usd > 0 && (p.mcap_usd ?? 0) > 0);
  const global = medianOf(live.map((p) => p.mcap_usd! / p.tvl_usd)) ?? model.multiple_floor;
  return Math.round(Math.min(model.multiple_cap, Math.max(model.multiple_floor, global)) * 1e4) / 1e4;
}

/** The peer multiple one protocol gets: its category's, or the global median when it has too few peers. */
export function categoryMultiple(p: SnapshotProtocol, comparables: Record<string, CategoryComparable>, globalMultiple: number): { multiple: number; peers: number } {
  const key = p.category ?? 'Other';
  const entry = comparables[key];
  if (entry !== undefined && entry.peers >= MODEL.min_peers) return { multiple: entry.multiple, peers: entry.peers };
  return { multiple: globalMultiple, peers: entry?.peers ?? 0 };
}

/** The multipliers and the implied value one protocol gets under `model`. */
export function impliedValue(
  protocol: SnapshotProtocol,
  asOf: string,
  model: ModelConstants,
  comparables: Record<string, CategoryComparable>,
  globalMultiple: number,
): { implied: number; multiple: number; peers: number; growthPct: number; growthMult: number; maturityMult: number; breadthMult: number; age: number | null } {
  const age = ageDays(asOf, protocol.listed_at);
  const { multiple, peers } = categoryMultiple(protocol, comparables, globalMultiple);
  const rawGrowth = finite(protocol.change_7d, 0);
  const growthPct = Math.min(model.growth_cap, Math.max(model.growth_floor, rawGrowth));
  const growthMult = 1 + (growthPct / 100) * model.growth_weight;
  const ageForModel = age ?? model.unknown_age_days;
  const maturityMult = model.maturity_floor + (Math.min(Math.max(ageForModel, 0), model.maturity_days) / model.maturity_days) * model.maturity_range;
  const breadthMult = 1 + model.breadth_per_chain * Math.min(Math.max(protocol.chains.length - 1, 0), model.breadth_max_chains);
  const base = protocol.tvl_usd * multiple;
  const implied = Math.max(1, Math.round(base * growthMult * maturityMult * breadthMult));
  return { implied, multiple, peers, growthPct, growthMult, maturityMult, breadthMult, age };
}

/** The headline sentence's figures: how many watchlist slugs, how many rows, how many live protocols. */
